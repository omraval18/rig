#!/usr/bin/env python3
"""Regenerate crates/rig-core/src/pricing/table.rs from models.dev (https://models.dev).

Prices are USD per million tokens, as models.dev lists them. Run by hand, review the diff, commit.
Only the providers rig ships defaults for are included; reasoning tokens are billed as output and
are not priced separately.
"""
import json
import pathlib
import sys
import urllib.request

SOURCE = "https://models.dev/api.json?type=all"
# rig provider name -> models.dev provider id
PROVIDERS = {
    "openai": "openai",
    "anthropic": "anthropic",
    "xai": "xai",
    "gemini": "google",
    "deepseek": "deepseek",
    "minimax": "minimax",
    "zai": "zai",
    "kimi": "moonshotai",
}
OUT = pathlib.Path(__file__).resolve().parent.parent / "crates/rig-core/src/pricing/table.rs"


def main() -> int:
    src = sys.argv[1] if len(sys.argv) > 1 else SOURCE
    with urllib.request.urlopen(src, timeout=60) as r:
        data = json.load(r)
    rows = []
    for ours, theirs in PROVIDERS.items():
        for mid, m in data.get(theirs, {}).get("models", {}).items():
            cost = m.get("cost")
            if not cost or "input" not in cost or "output" not in cost:
                continue
            rows.append((ours, mid, cost["input"], cost["output"],
                         cost.get("cache_read", 0.0), cost.get("cache_write", 0.0)))
    rows.sort()
    lines = [
        "//! Generated by scripts/gen_prices.py from models.dev. Do not edit by hand.",
        "//! USD per million tokens: [input, output, cache read, cache write].",
        "",
        "pub static PRICES: &[(&str, &str, [f64; 4])] = &[",
    ]
    for ours, mid, i, o, cr, cw in rows:
        vals = ", ".join(repr(float(x)) for x in (i, o, cr, cw))
        lines.append(f'    ("{ours}", "{mid}", [{vals}]),')
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(rows)} prices to {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
